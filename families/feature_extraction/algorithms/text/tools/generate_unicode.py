"""Generate native Unicode 16.0 tables with the locked CPython toolchain."""

from itertools import groupby
from pathlib import Path
import unicodedata

VERSION = "16.0.0"
LIMIT = 0x110000
WIDTH = 6


def ranges(predicate):
    for included, group in groupby(range(LIMIT), key=predicate):
        if included:
            start = end = next(group)
            for end in group:
                pass
            yield start
            yield end


def emit(name, values):
    encoded = "".join(f"{value:0{WIDTH}x}" for value in values)
    # Keep each table as one literal. This avoids compiling a chain of string
    # concatenations on the locked Mojo 1.0 compiler.
    return f'comptime {name}: StaticString = "{encoded}"\n'


def sigma_context(cp):
    # Python's final sigma rule skips case-ignorable characters, including
    # characters that also have the Cased property.
    char = chr(cp)
    if (char + "Σ").lower().endswith("ς"):
        return "cased"
    if ("A" + char + "Σ").lower().endswith("ς"):
        return "ignorable"
    return ""


def lowercase():
    for cp in range(LIMIT):
        char = chr(cp)
        lower = char.lower()
        if len(lower) == 1 and lower != char:
            yield cp
            yield ord(lower)
    assert [(ord(c), c.lower()) for c in map(chr, range(LIMIT)) if len(c.lower()) > 1] == [
        (0x0130, "i\u0307")
    ]


def main():
    assert unicodedata.unidata_version == VERSION
    context = [sigma_context(cp) for cp in range(LIMIT)]
    tables = {
        "WORD_RANGES": ranges(lambda cp: chr(cp).isalnum() or cp == 0x5F),
        "WHITESPACE_RANGES": ranges(lambda cp: chr(cp).isspace()),
        "CASED_RANGES": ranges(lambda cp: context[cp] == "cased"),
        "CASE_IGNORABLE_RANGES": ranges(lambda cp: context[cp] == "ignorable"),
        "LOWERCASE_PAIRS": lowercase(),
    }
    target = Path(__file__).resolve().parents[1] / "src/moxie/feature_extraction/_unicode_data.mojo"
    target.write_text(
        "# SPDX-License-Identifier: Unicode-3.0\n"
        "# Unicode 16.0.0 data generated by tools/generate_unicode.py.\n"
        "# Each code point is encoded as six hex digits. See LICENSE.unicode.\n\n"
        + "\n".join(emit(name, values) for name, values in tables.items()),
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
